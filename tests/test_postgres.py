PG_URL = os.environ.get("WHISKY_AI_TEST_PG_URL")
needs_pg = pytest.mark.skipif(PG_URL is None, reason="WHISKY_AI_TEST_PG_URL is not set")


# ---------- 変換ロジック (サーバー不要) ----------

def test_translate_placeholders_and_percent() -> None:
    assert translate("SELECT * FROM t WHERE a = ? AND b = ?") == "SELECT * FROM t WHERE a = %s AND b = %s"
    assert translate("SELECT 'is it?' , ?") == "SELECT 'is it?' , %s"  # リテラル内の ? はそのまま
    assert translate("SELECT 'it''s?', ?") == "SELECT 'it''s?', %s"
    assert translate("SELECT 100 % 7, '50%'") == "SELECT 100 %% 7, '50%%'"


def test_migration_to_postgres_types() -> None:
    sql = "CREATE TABLE x (id INTEGER PRIMARY KEY, n INTEGER NOT NULL, r REAL, t TEXT);"
    out = migration_to_postgres(sql, first=False)
    assert "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in out
    assert "n BIGINT NOT NULL" in out and "r DOUBLE PRECISION" in out and "t TEXT" in out
    assert "json_valid" not in out
    assert "FUNCTION json_valid" in migration_to_postgres(sql, first=True)


def test_all_migrations_use_portable_types() -> None:
    """マイグレーションは SQLite 版から機械変換するので、変換できない型を使っていないか確認する。"""
    for mig in db.load_migrations():
        code = "\n".join(line.split("--")[0] for line in mig.sql.splitlines())  # コメントを除く
        for bad in ("AUTOINCREMENT", "WITHOUT ROWID", "BLOB", "datetime(", "strftime("):
            assert bad not in code, f"{mig.name}: {bad}"


def test_pgrow_behaves_like_sqlite_row() -> None:
    row = PgRow((1, "a"), {"id": 0, "name": 1})
    assert (row["id"], row[1], tuple(row), row.keys()) == (1, "a", (1, "a"), ["id", "name"])
    assert dict([PgRow(("k", 2), {"axis": 0, "value": 1})]) == {"k": 2}


def test_lock_path_for_url_does_not_mangle() -> None:
    p = db.lock_path("postgresql://user:secret@host/db")
    assert p.parent == db.DEFAULT_DB_PATH.parent and p.name.startswith("pg-")
    assert "secret" not in str(p)
    assert db.lock_path("data/x.sqlite3") == Path("data/x.lock")


# ---------- db-copy (SQLite 同士はサーバー不要) ----------

def _seeded_sqlite(path: Path) -> None:
    assert main(["--db", str(path), "seed-sample"]) == 0
    assert main(["--db", str(path), "match"]) == 0
    assert main(["--db", str(path), "collect", "yahoo", "--keyword", "700ml", "--mock"]) == 0


def _counts(conn: sqlite3.Connection) -> dict[str, int]:
    return {t: conn.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0] for t in dbcopy.table_order()}


def test_table_order_covers_all_tables_in_fk_order() -> None:
    order = dbcopy.table_order()
    assert order.index("sources") < order.index("brands") < order.index("bottles") < order.index("listings")
    assert order.index("api_raw_responses") < order.index("price_observations")
    assert "watch_targets" in order and "price_alert_events" in order


def test_db_copy_sqlite_to_sqlite(tmp_path: Path) -> None:
    src, dst = tmp_path / "a.sqlite3", tmp_path / "b.sqlite3"
    _seeded_sqlite(src)
    assert main(["db-copy", "--from", str(src), "--to", str(dst)]) == 0
    a, b = db.connect(src), db.connect(dst)
    assert _counts(a) == _counts(b) and _counts(a)["listings"] > 0
    assert main(["db-copy", "--from", str(src), "--to", str(dst)]) == 2  # 移行先が空でない


# ---------- 実サーバー ----------

@pytest.fixture
def pg_url() -> Iterator[str]:
    """使い捨てスキーマを search_path にした接続 URL。"""
    assert PG_URL is not None
    schema = f"t_{uuid.uuid4().hex[:12]}"
    admin = PgConnection(PG_URL)
    admin.executescript(f"CREATE SCHEMA {schema}")
    admin.commit()
    sep = "&" if "?" in PG_URL else "?"
    yield f"{PG_URL}{sep}options=-csearch_path%3D{schema}"
    admin.executescript(f"DROP SCHEMA {schema} CASCADE")
    admin.commit()
    admin.close()


@needs_pg
def test_cli_end_to_end_on_postgres(pg_url: str, capsys: pytest.CaptureFixture[str]) -> None:
    assert main(["--db", pg_url, "seed-sample"]) == 0
    assert main(["--db", pg_url, "match"]) == 0
    assert main(["--db", pg_url, "watch", "add", "--keyword", "Aokawa", "--source", "yahoo"]) == 0
    assert main(["--db", pg_url, "alert", "add", "--bottle-id", "4", "--target-price", "7000"]) == 0
    capsys.readouterr()
    assert main(["--db", pg_url, "watch", "run", "--mock"]) == 0
    assert "値下がり: Aokawa 12 Years 700ml" in capsys.readouterr().out
    assert main(["--db", pg_url, "recommend", "--like", "1", "--limit", "3"]) == 0
    assert main(["--db", pg_url, "stats"]) == 0
    assert "listings.matched" in capsys.readouterr().out


@needs_pg
def test_db_copy_sqlite_to_postgres_and_back(tmp_path: Path, pg_url: str) -> None:
    src = tmp_path / "a.sqlite3"
    _seeded_sqlite(src)
    assert main(["db-copy", "--from", str(src), "--to", pg_url]) == 0
    a, pg = db.connect(src), db.connect(pg_url)
    assert _counts(a) == _counts(pg)
    # IDENTITY の採番が移行したデータの続きから始まる
    max_id = pg.execute("SELECT MAX(id) FROM sources").fetchone()[0]
    with pg:
        new_id = pg.execute("INSERT INTO sources (kind, title, retrieved_at) VALUES ('sample', 'x', 'now')"
                            ).lastrowid
    assert new_id == max_id + 1
    back = tmp_path / "b.sqlite3"
    assert main(["db-copy", "--from", pg_url, "--to", str(back)]) == 0
    assert _counts(db.connect(back))["sources"] == _counts(a)["sources"] + 1


@needs_pg
def test_errors_are_translated_and_connection_stays_usable(pg_url: str) -> None:
    conn = db.connect(pg_url)
    db.migrate(conn)
    with pytest.raises(sqlite3.IntegrityError):  # sqlite3 と同じ例外型
        conn.execute("INSERT INTO brands (name, category, source_id, created_at)"
                     " VALUES ('x', 'blended', 999, 'now')")
    assert conn.execute("SELECT COUNT(*) FROM brands").fetchone()[0] == 0  # 自動ロールバック済み
    with pytest.raises(sqlite3.IntegrityError), conn:
        conn.execute("INSERT INTO sources (kind, title, retrieved_at) VALUES ('sample', 'a', 'now')")
        conn.execute("INSERT INTO sources (kind, title, retrieved_at) VALUES ('bogus', 'b', 'now')")
    assert conn.execute("SELECT COUNT(*) FROM sources").fetchone()[0] == 0  # with ブロックごと取り消し
    with pytest.raises(sqlite3.IntegrityError):  # json_valid の CHECK も効く
        conn.execute("INSERT INTO api_raw_responses (marketplace, endpoint, request_params, status_code,"
                     " fetched_at) VALUES ('m', 'e', '{broken', 200, 'now')")
    assert db.migrate(conn) == []  # 再適用しない
