"""PostgreSQL 対応のテスト。

変換ロジックのテストは常に実行する。実サーバーが必要なテストは、環境変数
WHISKY_AI_TEST_PG_URL があるときだけ実行する (CI では PostgreSQL サービスを立てて実行)。
アプリ全体のテストは conftest の ``conn`` fixture で SQLite / PostgreSQL の両方に対して走る。
"""

from __future__ import annotations

import os
import sqlite3
import uuid
from collections.abc import Iterator
from pathlib import Path

import pytest

pytest.importorskip("psycopg")

from whisky_ai import db, dbcopy
from whisky_ai.cli import main
